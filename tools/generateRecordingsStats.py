#!/usr/bin/env python3
"""Regenerate docs/recordings-stats.md and its infographic from parsed events.

Reads page/src/misc/all-events.json (generated by tools/mdParser.js), computes
recording coverage, and writes docs/recordings-stats.md plus
docs/images/recordings-overall-events.png.

Usage:
    node tools/mdParser.js
    python3 tools/generateRecordingsStats.py [options]

Options:
    --date YYYY-MM-DD  snapshot date shown on the page (default: today)
    --no-image         skip the PNG infographic

Requirements: Pillow for the image (pip install pillow).
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
from collections import Counter
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
EVENTS = ROOT / "page" / "src" / "misc" / "all-events.json"
PAGE = ROOT / "docs" / "recordings-stats.md"
IMAGE = ROOT / "docs" / "images" / "recordings-overall-events.png"

PERIODS = ["2017-2020", "2021-2024", "2025", "2026", "2027-2028"]


def period_for(year: int) -> str:
    if year <= 2020:
        return "2017-2020"
    if year <= 2024:
        return "2021-2024"
    if year <= 2026:
        return str(year)
    return "2027-2028"


def is_playlist(url: str) -> bool:
    return "list=" in url


def is_youtube(url: str) -> bool:
    host = urlparse(url).netloc.lower()
    return host == "youtu.be" or host.endswith(".youtube.com") or host == "youtube.com"


def summarize(events: list[dict]) -> dict:
    total = len(events)
    recorded = [event for event in events if event.get("recordings")]
    links = [link for event in recorded for link in event["recordings"]]

    by_period = {name: {"events": 0, "recorded": 0, "links": 0, "multi": 0,
                        "playlists": 0, "videos": 0}
                 for name in PERIODS}
    for event in events:
        date = dt.datetime.fromtimestamp(event["date"][0] / 1000, dt.timezone.utc)
        bucket = by_period[period_for(date.year)]
        bucket["events"] += 1
        entries = event.get("recordings") or []
        if not entries:
            continue
        bucket["recorded"] += 1
        bucket["links"] += len(entries)
        bucket["multi"] += len(entries) > 1
        bucket["playlists"] += sum(1 for link in entries if is_playlist(link["url"]))
        bucket["videos"] += sum(1 for link in entries if not is_playlist(link["url"]))

    top_counter: Counter[tuple[str, dt.date, int]] = Counter()
    for event in recorded:
        date = dt.datetime.fromtimestamp(event["date"][0] / 1000, dt.timezone.utc)
        top_counter[(event["name"], date.date(), len(event["recordings"]))] += 1

    top = sorted(top_counter, key=lambda row: (-row[2], row[1], row[0]))
    top = [row for row in top if row[2] >= 5]

    playlists = sum(1 for link in links if is_playlist(link["url"]))
    return {
        "total": total,
        "recorded": len(recorded),
        "links": len(links),
        "multi": sum(1 for event in recorded if len(event["recordings"]) > 1),
        "playlists": playlists,
        "videos": len(links) - playlists,
        "youtube": sum(1 for link in links if is_youtube(link["url"])),
        "by_period": by_period,
        "top": top,
    }


def percent(part: int, whole: int) -> str:
    return f"{part / whole * 100:.2f}%" if whole else "0.00%"


def pct(part: int, whole: int) -> float:
    return part / whole * 100 if whole else 0.0


def markdown(data: dict, updated: str) -> str:
    total = data["total"]
    rows = []
    for name in PERIODS:
        bucket = data["by_period"][name]
        label = name.replace("-", "–")
        rows.append(
            f"| {label} | {bucket['events']:,} | {bucket['recorded']:,} | "
            f"{percent(bucket['recorded'], bucket['events'])} | {bucket['links']:,} | "
            f"{bucket['multi']:,} | {bucket['playlists']:,} | {bucket['videos']:,} |"
        )
    rows.append(
        f"| **Total** | **{total:,}** | **{data['recorded']:,}** | "
        f"**{percent(data['recorded'], total)}** | **{data['links']:,}** | "
        f"**{data['multi']:,}** | **{data['playlists']:,}** | **{data['videos']:,}** |"
    )
    top_rows = [
        f"| {name} | {date.isoformat()} | {count} |"
        for name, date, count in data["top"]
    ]

    return f"""# Recording statistics

Last updated: {updated}

This page summarizes recording coverage in the current repository data.
`METADATA.csv` is the source of record; `tools/mdParser.js` derives the event
data used by the website. Regenerate this page with
`python3 tools/generateRecordingsStats.py` after metadata changes.

An event counts as recorded when it has at least one public recording link.
Recording links include playlists, individual videos, archives, and organizer
pages. Links are counted per event entry, not as the number of videos contained
inside a playlist.

## Overall

| Metric | Value |
|---|---:|
| Event entries | {total:,} |
| Events with at least one recording | {data['recorded']:,} ({percent(data['recorded'], total)}) |
| Recording links | {data['links']:,} |
| Events with multiple recordings | {data['multi']:,} |
| Playlist links | {data['playlists']:,} ({percent(data['playlists'], data['links'])}) |
| Video or other links | {data['videos']:,} ({percent(data['videos'], data['links'])}) |
| YouTube links | {data['youtube']:,} ({percent(data['youtube'], data['links'])}) |

![Conference events and recordings across all event years](images/recordings-overall-events.png)

## By event year

Events are grouped by the year of their start date.

| Event year | Event entries | With recordings | Coverage | Recording links | Multiple recordings | Playlists | Videos / other |
|---|---:|---:|---:|---:|---:|---:|---:|
{chr(10).join(rows)}

Future years are included in the event-entry totals but naturally have no
recordings yet. Coverage therefore describes the current metadata snapshot, not
a permanent property of an event year.

## Events with the most recording links

This table lists every event with five or more recording links. Ties are ordered
by date and event name.

| Event | Date | Recording links |
|---|---|---:|
{chr(10).join(top_rows)}

## Link classification

Playlist links are identified by a `list=` URL parameter. Everything else,
including individual videos, channel pages, and archive pages, is classified as
video/other. This is a URL-based classification and does not count the
individual videos contained within a playlist.

Recording numbers are a snapshot of the public links currently recorded in
`METADATA.csv`. Missing links mean no public recording has been recorded in the
metadata, not that no recording exists. Re-run the metadata parser and this
script after data changes to keep this page and its infographic synchronized
with the generated event data.
"""


def draw_image(data: dict, updated: str) -> None:
    from PIL import Image, ImageDraw, ImageFont

    BLUE = "#2864A5"
    NAVY = "#142B43"
    MID_BLUE = "#54708D"
    MINT = "#28A997"
    PALE_BLUE = "#EAF2FA"
    PALE_MINT = "#DDF4EE"
    PALE_ORANGE = "#FFF1DF"
    ORANGE = "#E99A3D"
    GRAY = "#DCE5EE"
    OFF_WHITE = "#F5F8FC"

    def font(size: int, bold: bool = False):
        for directory in (
            Path("/System/Library/Fonts/Supplemental"),
            Path("/usr/share/fonts/truetype/dejavu"),
        ):
            name = "Arial Bold.ttf" if bold else "Arial.ttf"
            candidate = directory / name
            if candidate.exists():
                return ImageFont.truetype(str(candidate), size)
            name = "DejaVuSans-Bold.ttf" if bold else "DejaVuSans.ttf"
            candidate = directory / name
            if candidate.exists():
                return ImageFont.truetype(str(candidate), size)
        return ImageFont.load_default()

    def text(draw, xy, value, size, color=NAVY, bold=False, anchor=None):
        draw.text(xy, value, font=font(size, bold), fill=color, anchor=anchor)

    def center(draw, x, y, value, size, color=NAVY, bold=False):
        text(draw, (x, y), value, size, color, bold, anchor="mm")

    def rounded(draw, box, radius, fill):
        draw.rounded_rectangle(box, radius=radius, fill=fill)

    width, height = 1600, 1500
    image = Image.new("RGB", (width, height), OFF_WHITE)
    draw = ImageDraw.Draw(image)

    text(draw, (72, 48), "Conference events & recordings", 56, NAVY, True)
    text(draw, (74, 125), f"Overall statistics across all event years  /  {updated}", 28, MID_BLUE)
    rounded(draw, (1280, 59, 1528, 111), 25, PALE_BLUE)
    center(draw, 1404, 85, "developers.events", 25, BLUE, True)

    cards = [
        (68, 200, 544, 418, f"{data['total']:,}", "event entries", BLUE, PALE_BLUE),
        (562, 200, 1038, 418, f"{data['recorded']:,}", "events with recordings", MINT, PALE_MINT),
        (1056, 200, 1532, 418, f"{data['links']:,}", "recording links", ORANGE, PALE_ORANGE),
    ]
    for left, top, right, bottom, value, label, accent, background in cards:
        rounded(draw, (left, top, right, bottom), 24, background)
        center(draw, (left + right) / 2, top + 72, value, 64, accent, True)
        center(draw, (left + right) / 2, top + 157, label, 25, NAVY, True)

    center(
        draw, 800, 468,
        f"{percent(data['recorded'], data['total'])} of all event entries have at least one recording link",
        28, NAVY, True,
    )
    text(draw, (72, 550), "Events compared by year", 40, NAVY, True)
    rounded(draw, (950, 558, 1024, 582), 9, GRAY)
    text(draw, (1038, 553), "All events", 24, MID_BLUE)
    rounded(draw, (1190, 558, 1264, 582), 9, BLUE)
    text(draw, (1278, 553), "With recordings", 24, MID_BLUE)

    bar_left, bar_width, row_start, row_height = 330, 1110, 650, 137
    scale = max(bucket["events"] for bucket in data["by_period"].values()) or 1
    for index, name in enumerate(PERIODS):
        bucket = data["by_period"][name]
        y = row_start + index * row_height
        text(draw, (74, y + 37), name.replace("-", "–"), 29, NAVY, True)
        total_width = round(bar_width * bucket["events"] / scale)
        rounded(draw, (bar_left, y, bar_left + total_width, y + 42), 10, GRAY)
        text(draw, (bar_left + 18, y + 8), f"{bucket['events']:,} events", 24, NAVY, True)
        recorded_width = round(bar_width * bucket["recorded"] / scale)
        if recorded_width:
            rounded(draw, (bar_left, y + 58, bar_left + recorded_width, y + 100), 10, BLUE)
        else:
            draw.line((bar_left, y + 79, bar_left + 4, y + 79), fill=BLUE, width=5)
        label_left = bar_left + recorded_width + 18 if recorded_width else bar_left + 18
        text(draw, (label_left, y + 66), f"{bucket['recorded']:,} with recordings", 23, NAVY, True)
        detail = f"{bucket['links']:,} recording links"
        if name == "2027-2028":
            detail += "  /  upcoming"
        rounded(draw, (1210, y + 51, 1532, y + 111), 18, PALE_MINT if bucket["links"] else PALE_BLUE)
        center(draw, 1371, y + 81, detail, 22, MID_BLUE, True)

    center(draw, 800, 1390, "An event is counted as recorded when it has at least one public recording link in METADATA.csv.", 23, MID_BLUE)
    center(draw, 800, 1433, "Totals include event entries from 2017 through 2028. Recording links include playlists, videos, and archives.", 23, MID_BLUE)

    IMAGE.parent.mkdir(parents=True, exist_ok=True)
    image.save(IMAGE, "PNG", optimize=True, dpi=(144, 144))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--date", help="snapshot date shown on the page (YYYY-MM-DD)")
    parser.add_argument("--no-image", action="store_true", help="skip the PNG infographic")
    args = parser.parse_args()

    updated = args.date or dt.date.today().strftime("%-d %B %Y")
    events = json.loads(EVENTS.read_text())
    data = summarize(events)

    PAGE.write_text(markdown(data, updated))
    print(PAGE)

    if not args.no_image:
        try:
            draw_image(data, updated)
            print(IMAGE)
        except ImportError:
            print("Pillow not installed; skipped the infographic (pip install pillow)")


if __name__ == "__main__":
    main()
